"""Write site/data.js, the data of the leaderboard and dashboard, from the published results and the registry.

    python -m translate_bench.export.site_data          # write site/data.js
    python -m translate_bench.export.site_data --check  # exit 1 if site/data.js differs from the results

The page aggregates any selection of directions and text types from the cell values here, with the
release's rule (sentence and passage cells 50:50 in each direction, directions weighted equally).
For paired intervals it gets each scored item's COMET-22 (in millionths) and the release's 2,000
document draws, so it can compute the same paired document bootstrap as `translate-bench verify`
for any pair of systems and any selection. For the judge it gets, per system and cell, the counts of
the judge v1 rows (wins, losses, judged ties, identical outputs; error-free and annotated items), so
it aggregates the judge over a selection the way `translate-bench judge` does; the build checks that
these counts reproduce the published judge summary over all directions. When results/ltb-v1/ exists,
each system also gets its hard-cases pass rate with its 95% interval (`ltb`, null for a system without a
complete score), and `hard_cases` names the item count and
the verifier. When results/v1.1/overall.json exists, each system gets its entry there (`overall`: the
Overall score, null for a system without one, its three pillars with their directions, its coverage and
the languages it misses); below 18 directions `ltb` is the pass rate on the items in the directions it
covers, with the pass rate on all of them under `ltb.all`.

The file holds numbers, identifiers and the registry's names and settings; no test text, reference
or output is read or written.
"""

import argparse
import hashlib
import json
import sys
from collections import Counter
from pathlib import Path

from translate_bench import aggregate, schema
from translate_bench.export.facts import JUDGE_LABELS, REFERENCE, Facts

OUT = Path("site") / "data.js"
SCHEMA = "translate-bench/site@1"
PREFIX = ("// Generated by translate_bench/export/site_data.py from results/v1/, results/ltb-v1/, results/v1.1/ and "
          "configs/systems.json. Do not edit.\n")
TYPE_KEYS = {"sentence": "s", "passage": "p"}
SOURCES = ("results/v1/summary.json", "results/v1/speed.json", "results/v1/judge/summary.json",
           "results/ltb-v1/summary.json", "results/v1.1/overall.json")


def r6(x):
    return aggregate.round6(x)


def cell_key(kind, direction):
    return f"{TYPE_KEYS[kind]}:{direction}"


def system_meta(facts, sid):
    s = facts.systems[sid]
    block = facts.block(sid)
    speed = facts.speed_entry(sid)
    weights = s.get("weights") or {}
    runtime = s.get("runtime") or {}
    client = s.get("client") or {}
    mode = s.get("request_mode") or {}
    per_request = mode.get("items_per_request")
    entry = dict(
        id=sid, name=s["name"], developer=s["developer"], kind=s["kind"], family=s["family"],
        size=s.get("size_label"), parameters=s.get("parameters"), moe=s.get("mixture_of_experts"),
        quantization=weights.get("quantization"), format=weights.get("format"), license=weights.get("license"),
        runtime=runtime.get("name"), client=client.get("name"), via=client.get("via"), reasoning=s.get("reasoning"),
        per_request=per_request if isinstance(per_request, dict) else dict(sentence=per_request, passage=per_request),
        concurrent=mode.get("concurrent_requests"), unsupported=s.get("unsupported_languages"),
        support_note=s.get("support_note"), prompt=s.get("prompt_profile"),
        completion=block["completion"],
        directions={TYPE_KEYS[k]: len(v) for k, v in block["directions"].items()},
    )
    if s["kind"] == "local":
        entry.update(
            download=speed.get("download_bytes") or weights.get("size_bytes"),
            memory=speed.get("peak_memory_gib"), memory_measured=speed.get("memory_measured"),
            load=speed.get("load_s"),
            speed={TYPE_KEYS[k]: dict(median=speed[k]["median_s"], p90=speed[k]["p90_s"],
                                      ok=speed[k]["successful"], attempts=speed[k]["attempts"])
                   for k in schema.TYPES if speed.get(k)},
            flagged=sum(speed.get("flagged") or []),
            speed_date=speed.get("date"))
    else:
        ref = speed.get("reference") or {}
        entry["reference"] = {TYPE_KEYS[k]: dict(seconds=r6(ref[k]["seconds_per_item"]),
                                                 tokens=r6(ref[k].get("tokens_per_item")),
                                                 usd=r6(ref[k].get("estimated_usd_per_1000_items")))
                              for k in schema.TYPES if ref.get(k)} or None
    return entry


def judge_block(facts):
    systems = {}
    for sid in facts.systems:
        entry = {}
        for scope in ("all", "sentence", "passage"):
            vs = facts.judge.versus_reference(sid, scope)
            ef = facts.judge.error_free(sid, scope)
            if vs or ef:
                entry[scope] = dict(
                    vs=None if vs is None else dict(n=vs["n"], wins=vs["wins"], losses=vs["losses"], ties=vs["ties"],
                                                    identical=vs["identical"], preferred=r6(vs["preferred"]),
                                                    net=vs["net"], net95=vs["net_95"]),
                    ef=None if ef is None else dict(n=ef["n"], value=r6(ef["error_free"]),
                                                    ci=ef.get("error_free_95"), directions=ef.get("directions")))
        if entry:
            systems[sid] = entry
    label = JUDGE_LABELS[facts.judge_source]
    return dict(source=facts.judge_source, label=label["en"], description=label["long_en"], model=facts.judge.model,
                model_name=facts.name(facts.judge.model), reference=REFERENCE, systems=systems, **judge_cells(facts))


def judge_cells(facts):
    """Per system and cell ("s:en-ja"), the counts of the judge v1 rows that are not missing.

    pairwise: [wins, losses, judged ties, identical outputs]; errors: [items with no error counted, items
    annotated]. Within a cell the items weigh equally, so these counts give the release's aggregation of any
    selection (`aggregate_cells`), and the build checks them against the published summary."""
    from translate_bench import judge_results

    _, files = judge_results.load_rows(facts.root)
    out = dict(per_cell=facts.judge.data["sample"]["per_cell"], pairwise={}, errors={})
    for stage in ("pairwise", "errors"):
        for sid, data in sorted(files[stage].items()):
            counts = {}
            for r in data["rows"]:
                if r["status"] == "missing":
                    continue
                empty = [0, 0, 0, 0] if stage == "pairwise" else [0, 0]
                c = counts.setdefault(cell_key(r["type"], r["direction"]), empty)
                if stage == "pairwise":
                    c[{"system": 0, "against": 1}.get(r["winner"], 2 if r["status"] == "judged" else 3)] += 1
                else:
                    c[0] += r["critical"] + r["major"] + r["minor"] == 0
                    c[1] += 1
            order = {cell_key(t, d): (schema.DIRECTIONS.index(d), t) for d in schema.DIRECTIONS for t in schema.TYPES}
            out[stage][sid] = dict(sorted(counts.items(), key=lambda kv: order[kv[0]]))
    tol = 5.01e-5  # the summary rounds to four decimals
    for sid in facts.systems:
        for scope, types in (("all", schema.TYPES), ("sentence", ("sentence",)), ("passage", ("passage",))):
            keys = [TYPE_KEYS[t] for t in types]
            vs, ef = facts.judge.versus_reference(sid, scope), facts.judge.error_free(sid, scope)
            mine = aggregate_cells(out["pairwise"].get(sid, {}), schema.DIRECTIONS, keys, "pairwise")
            if (vs is None) != (mine is None) or vs and (
                    mine["n"] != vs["n"] or abs(mine["net"] - vs["net"]) > tol
                    or (vs["preferred"] is None) != (mine["preferred"] is None)
                    or vs["preferred"] is not None and abs(mine["preferred"] - vs["preferred"]) > tol):
                raise ValueError(f"judge cells of {sid} do not reproduce the published pairwise summary ({scope})")
            mine = aggregate_cells(out["errors"].get(sid, {}), schema.DIRECTIONS, keys, "errors")
            if (ef is None) != (mine is None) or ef and (
                    mine["n"] != ef["n"] or abs(mine["error_free"] - ef["error_free"]) > tol):
                raise ValueError(f"judge cells of {sid} do not reproduce the published error summary ({scope})")
    return out


def aggregate_cells(cells, directions, types, stage):
    """The release's judge aggregation of a selection from per-cell counts; app.js judgeScope does the same.

    With both text types, only the directions with items of both count; each counted direction weighs
    equally, its types equally, and the items of a cell equally. None without any item."""
    used = [d for d in directions if all(cells.get(f"{t}:{d}") for t in types)] if len(types) > 1 else \
        [d for d in directions if cells.get(f"{types[0]}:{d}")]
    if not used:
        return None
    share = 1 / (len(used) * len(types))
    if stage == "errors":
        n = sum(cells[f"{t}:{d}"][1] for d in used for t in types)
        return dict(n=n, error_free=sum(share * cells[f"{t}:{d}"][0] / cells[f"{t}:{d}"][1]
                                        for d in used for t in types))
    w = lambda k: sum(share * cells[f"{t}:{d}"][k] / sum(cells[f"{t}:{d}"]) for d in used for t in types)  # noqa: E731
    wins, losses = w(0), w(1)
    n = sum(sum(cells[f"{t}:{d}"]) for d in used for t in types)
    return dict(n=n, net=wins - losses, preferred=wins / (wins + losses) if wins + losses else None)


def cells_and_items(facts):
    """Cell values of every system, the canonical item order of each cell and the item scores."""
    release = facts.release
    items = {}  # cell key -> sorted item ids
    docs = sorted(release.weights)
    doc_index = {d: i for i, d in enumerate(docs)}
    manifest = schema.read_jsonl(facts.root / "datasets" / "items.jsonl")
    by_cell = {}
    for it in manifest:
        by_cell.setdefault(cell_key(it["type"], it["direction"]), []).append(it)
    item_docs = {}
    for key, members in by_cell.items():
        members.sort(key=lambda it: it["id"])
        items[key] = [m["id"] for m in members]
        item_docs[key] = [doc_index[m["doc"]] for m in members]
    cells, scores = {}, {}
    for sid in release.published:
        table = release.tables[sid]
        rows = {r["id"]: r for r in release.rows[sid]}
        cells[sid], scores[sid] = {}, {}
        for (kind, direction), (attempted, ok) in sorted(table.counts.items(),
                                                          key=lambda x: (schema.DIRECTIONS.index(x[0][1]), x[0][0])):
            key = cell_key(kind, direction)
            comet_items = table.items["comet22"][kind, direction]
            chrf_items = table.items["chrf"][kind, direction]
            mx = {}
            for name in ("metricx24_ref", "metricx24_qe"):
                values = [rows[i][name] for i in comet_items if rows[i].get(name) is not None]
                mx[name] = r6(sum(values) / len(values)) if values else None
            cells[sid][key] = [r6(aggregate.cell_score(comet_items, "comet22")),
                               r6(aggregate.cell_score(chrf_items, "chrf")), mx["metricx24_ref"],
                               mx["metricx24_qe"], len(comet_items), ok, attempted]
            scores[sid][key] = ",".join("" if i not in comet_items else str(round(comet_items[i][1] * 1e6))
                                        for i in items[key])
    multiplicities = []
    for d in docs:
        w = release.weights[d][1:]
        if w.max() > 9:
            raise ValueError("A document multiplicity above 9 does not fit the one-digit encoding")
        multiplicities.append("".join(str(int(x)) for x in w))
    boot = dict(draws=len(release.weights[docs[0]]) - 1, seed_string=facts.summary["bootstrap"]["seed_string"],
                docs=len(docs), m=multiplicities)
    return cells, items, item_docs, scores, boot


def hard_cases(root):
    """{system: {rate, ci, passed, items, directions[, all]}}: the Overall score's hard-cases pillar with its 95%
    interval, or {} without the track. That is the pass rate on the items of results/ltb-v1/ in the release's
    directions, or for a system scored over fewer directions on the items in the directions it covers; `all`
    then gives the pass rate on all of them."""
    from translate_bench import ltb

    if not ltb.exists(root):
        return {}
    summary = schema.read_json(root / ltb.BASE / "summary.json")
    entries = overall_entries(root)
    n = len(schema.DIRECTIONS)
    out = {}
    for sid, e in summary["systems"].items():
        ours, covered = e["our_directions"], e.get("covered")
        figure = lambda b: dict(rate=r6(b["passed"] / b["items"]), ci=b["ci95"], passed=b["passed"],  # noqa: E731
                                items=b["items"])
        if covered and covered["items"] and (entries.get(sid) or {}).get("directions", {}).get("hard_cases", n) < n:
            out[sid] = dict(figure(covered), directions=covered["directions"], all=figure(ours))
        else:
            out[sid] = dict(figure(ours), directions=n)
    return out


def hard_cases_meta(root):
    """The item count and the verifier's name of the hard-cases column, or None without the track."""
    from translate_bench import ltb

    if not ltb.exists(root):
        return None
    summary = schema.read_json(root / ltb.BASE / "summary.json")
    return dict(items=summary["dataset"]["our_direction_items"], verifier=summary["verifier"]["name"],
                benchmark="Last Translation Benchmark")


def overall_entries(root):
    """{system: {overall, standard, reliability, hard_cases, coverage, directions, hard_cases_items,
    missing_languages}} of results/v1.1/overall.json, or {}."""
    from translate_bench import overall

    if not overall.exists(root):
        return {}
    return schema.read_json(root / overall.PATH)["systems"]


def overall_rule(root):
    """The coverage rule of the Overall score, or None without results/v1.1/overall.json."""
    from translate_bench import overall

    if not overall.exists(root):
        return None
    data = schema.read_json(root / overall.PATH)
    return dict(min_directions=data["min_directions"], directions=data["directions"])


def sources(root):
    out = {}
    for rel in SOURCES:
        path = root / rel
        if path.is_file():
            out[rel] = hashlib.sha256(path.read_bytes()).hexdigest()
    return out


def build(root):
    facts = Facts(root)
    cells, items, item_docs, scores, boot = cells_and_items(facts)
    families = {}
    for sid, s in facts.systems.items():
        if s["kind"] == "local" and s.get("parameters"):
            families.setdefault(s["family"], []).append(sid)
    families = {f: sorted(m, key=lambda x: facts.systems[x]["parameters"])
                for f, m in families.items() if len(m) > 1}
    counts = Counter(s["kind"] for s in facts.systems.values())
    hard = hard_cases(root)
    totals = overall_entries(root)
    return dict(
        schema=SCHEMA, release=schema.RELEASE, sources=sources(root),
        machine=facts.speed["machine"],
        counts=dict(systems=len(facts.systems), local=counts["local"], cloud=counts["cloud"],
                    directions=len(schema.DIRECTIONS),
                    items=len(schema.DIRECTIONS) * sum(schema.CELL_SIZE.values())),
        languages=[dict(code=k, name=schema.LANGUAGE_NAMES[k]) for k in schema.LANGUAGES],
        directions=list(schema.DIRECTIONS),
        bootstrap=dict(description=facts.summary["bootstrap"]["description"], draws=boot["draws"],
                       seed_string=boot["seed_string"]),
        systems=[dict(system_meta(facts, sid), ltb=hard.get(sid), overall=totals.get(sid)) for sid in facts.systems],
        hard_cases=hard_cases_meta(root),
        overall_rule=overall_rule(root),
        families=families,
        judge=judge_block(facts),
        cells=cells,
        items=dict(docs=item_docs, count={k: len(v) for k, v in items.items()}),
        scores=scores,
        boot=dict(docs=boot["docs"], m=boot["m"]),
    )


def render(data):
    return PREFIX + "window.TB_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"


def parse(text):
    start = text.index("window.TB_DATA = ") + len("window.TB_DATA = ")
    return json.loads(text[start:text.rindex(";")])


def check(root, path):
    """Differences between the committed data file and a rebuild (numbers within 1.5e-6 are equal)."""
    from translate_bench.verify import differences

    if not path.is_file():
        return [f"{path.relative_to(root)}: missing"]
    try:
        published = parse(path.read_text(encoding="utf-8"))
    except ValueError:
        return [f"{path.relative_to(root)}: not a data file written by this generator"]
    return differences(published, json.loads(json.dumps(build(root))), "site/data.js", limit=20)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, help="the translate-bench checkout (default: found from here)")
    parser.add_argument("--check", action="store_true", help="compare with the committed file instead of writing")
    args = parser.parse_args(argv)
    root = schema.find_root(args.root)
    path = root / OUT
    if args.check:
        found = check(root, path)
        for line in found:
            print(line)
        print(f"site data: {'differs from the results' if found else 'matches the results'} ({OUT})")
        return 1 if found else 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(build(root)), encoding="utf-8")
    print(f"wrote {OUT} ({path.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
